def main() -> int:
    man = json.loads((ART_DIR / "asset_manifest.json").read_text())
    ver = json.loads((DOC_DIR / "verification.json").read_text())
    DOC_DIR.mkdir(parents=True, exist_ok=True)
    fig_name = figure(man, DOC_DIR / "fig_locator_coverage.png")
    env = json.loads((pathlib.Path("runs") / PACKAGE_ID / ("kf_result.%s.json" % PACKAGE_ID)).read_text())
    md = build_md(man, ver, fig_name, env)
    (DOC_DIR / ("KF-RESULT-%s.md" % PACKAGE_ID)).write_text(md)
    print("wrote", DOC_DIR / ("KF-RESULT-%s.md" % PACKAGE_ID), "and", DOC_DIR / fig_name)
    print("json blocks(fenced):", len(re.findall(r"^```json$", md, flags=re.M)))
    return 0


