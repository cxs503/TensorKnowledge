#!/usr/bin/env python3
"""wp-11478-01 · publish the KF-RESULT report to the platform.

Body = docs/wp-11478-01/KF-RESULT-wp-11478-01.md verbatim (it already carries the single json block).
Title = "KF-RESULT wp-11478-01"; tags include kf-wp:wp-11478-01. One figure is embedded as
png_base64 (asset span map, generated by scripts/kf_figure_11478.py).

Credentials come from the environment; nothing secret is written to the tree.
Idempotent by design: if runs/wp-11478-01/publish_11478.json records a successful publish this
script skips (pass --force to publish again) so a re-run cannot spam duplicate reports.

Usage: python3 scripts/kf_publish_11478.py [--force]
"""
from __future__ import annotations

import base64
import json
import os
import pathlib
import sys
import urllib.error
import urllib.request

API = os.environ.get("TENSOR_API_BASE", "http://127.0.0.1:8010/api/v1").rstrip("/")
PACKAGE_ID = "wp-11478-01"
REPORT_ID = "11478"
RUN_DIR = pathlib.Path("runs") / PACKAGE_ID
DOC = pathlib.Path("docs") / PACKAGE_ID / f"KF-RESULT-{PACKAGE_ID}.md"
PNG = pathlib.Path("docs") / PACKAGE_ID / "asset_span_map.png"
RECORD = RUN_DIR / "publish_11478.json"
MISSION_ID = 15724

CAPTION = ("wp-11478-01 资产登记图：A=21 个资产 locator 在报告字符轴上的位置（按 resolution 着色，"
           "覆盖 3180/4710 字符=67.5%）；B=按 resolution 重数；C=按章节①-⑥计数。"
           "数字由 scripts/kf_figure_11478.py 从 asset_manifest.json 程序化导出，零手抄。")
assert len(CAPTION) <= 300, len(CAPTION)


def call(path: str, body: dict | None, tok: str | None = None, timeout: int = 180):
    headers = {"Content-Type": "application/json"}
    if tok:
        headers["Authorization"] = f"Bearer {tok}"
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(API + path, data=data, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, r.read().decode()
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read().decode()


def main() -> int:
    force = "--force" in sys.argv
    if RECORD.exists() and not force:
        prev = json.loads(RECORD.read_text())
        if prev.get("status") in (200, 201):
            print(json.dumps({"skipped": True, "published_report_id": prev.get("report_id")}))
            return 0

    st, body = call("/auth/login", {"username": os.environ["TENSOR_AGENT_USER"],
                                    "password": os.environ["TENSOR_AGENT_PASS"]})
    if st != 200:
        print(f"login failed {st}: {body[:200]}")
        return 2
    tok = json.loads(body)["access_token"]

    manifest = json.loads((pathlib.Path("docs") / PACKAGE_ID / "asset_manifest.json").read_text())
    markdown = DOC.read_text()
    assert markdown.count("```json") == 1, "KF-RESULT doc must carry exactly one json block"

    figures = []
    if PNG.exists():
        figures.append(dict(name=PNG.name, caption=CAPTION,
                            png_base64=base64.b64encode(PNG.read_bytes()).decode()))

    payload = {
        "title": f"KF-RESULT {PACKAGE_ID}",
        "summary": (
            f"{PACKAGE_ID} (01-asset-registration, report {REPORT_ID}): markdown sha256 "
            f"{manifest['source']['hash'][:16]}… recomputed equal to the contract hash "
            f"(4710 chars / 8163 B); {manifest['counts']['assets']} assets registered with byte-exact "
            f"locators ({manifest['counts']['by_resolution']}); every locator re-resolves uniquely in a "
            "freshly fetched copy; 4 claims carry explicit status (none marked verified); "
            "8 external-repo assets honestly reported unresolved inside this worktree."
        ),
        "scenario_key": manifest["source"]["scenario_key"],
        "mission_id": MISSION_ID,
        "tags": ["kf-wp:" + PACKAGE_ID, "01-asset-registration", f"report:{REPORT_ID}",
                 "lane:C", "draft", "knowledge-factory"],
        "markdown": markdown,
        "figures": figures,
    }
    st, resp = call("/tensor/reports", payload, tok)
    out = {"status": st, "response_head": resp[:400], "title": payload["title"],
           "tags": payload["tags"], "figures": [f["name"] for f in figures],
           "doc": str(DOC), "doc_sha256_matches": None}
    try:
        parsed = json.loads(resp)
        out["report_id"] = (parsed.get("data") or parsed).get("id")
    except Exception:
        out["report_id"] = None
    RUN_DIR.mkdir(parents=True, exist_ok=True)
    if force and RECORD.exists():
        try:
            prev = json.loads(RECORD.read_text())
        except Exception:
            prev = None
        out["supersedes"] = prev.get("report_id") if prev else None
        out["history"] = (prev.get("history") or []) + [prev] if prev else []
    RECORD.write_text(json.dumps(out, ensure_ascii=False, indent=2))
    print(json.dumps({"status": st, "report_id": out["report_id"], "figures": out["figures"]},
                     ensure_ascii=False))
    return 0 if st in (200, 201) else 1


if __name__ == "__main__":
    sys.exit(main())