#!/usr/bin/env python3
"""Render docs/ke/m8554-audit.md from the built mapping + validation results.

    python scripts/render_ke_audit.py          # write the document
    python scripts/render_ke_audit.py --check  # exit 1 if the committed document is stale

Every number in the rendered document is read out of mappings/m8554.json and
runs/ke_mapping_validation.json, so the audit table can never drift from the
data it claims to describe (no hand transcription).
"""

from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = "docs/ke/m8554-audit.md"


def load(rel: str) -> dict:
    path = os.path.join(ROOT, rel)
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(out)


def render() -> str:
    m = load("mappings/m8554.json")
    v = load("runs/ke_mapping_validation.json")
    audit = m["audit"]
    src = m["source"]

    lines: list[str] = []
    lines.append("# m8554 projection audit (generated)")
    lines.append("")
    lines.append("> Generated by `scripts/render_ke_audit.py` from `mappings/m8554.json` and "
                 "`runs/ke_mapping_validation.json`. Do not edit by hand; rebuild the mapping and "
                 "re-render instead. Specification: [`mapping-spec.md`](mapping-spec.md).")
    lines.append("")
    lines.append(f"**Source package:** `{src['repository']}` `{src['branch']}` @ `{src['commit']}` "
                 f"→ `{src['path']}` (frozen snapshot in `{m['snapshot_dir']}`).")
    lines.append("")
    lines.append(f"**Policies:** projection `{m['projection_version']}` · mapping `{m['policy_version']}` "
                 f"· review `{m['review_policy_version']}` · spec v{m['spec_version']}.")
    lines.append("")

    lines.append("## 1. Coverage by contract")
    lines.append("")
    rows = []
    for contract, row in audit["by_contract"].items():
        classes = ", ".join(f"{k}={n}" for k, n in sorted(row["by_loss_class"].items()))
        rows.append([contract, row["records"], row["leaf_paths"], row["covered"],
                     row["uncovered"], classes])
    rows.append(["**total**", audit["records"], audit["leaf_paths_total"],
                 audit["leaf_paths_projected"], audit["leaf_paths_uncovered"], ""])
    lines.append(table(["contract", "records", "leaf paths", "projected", "uncovered",
                        "loss classes"], rows))
    lines.append("")
    lines.append(f"Uncovered leaf paths: **{audit['leaf_paths_uncovered']}** · semantic-loss "
                 f"disclosures: **{audit['disclosures']}** "
                 f"(L4={audit['disclosure_classes']['L4']}, L1={audit['disclosure_classes']['L1']}) · "
                 f"edges: **{audit['edges']}** · vector facets: **{audit['vector_facets']}**.")
    lines.append("")

    lines.append("## 2. Per-record projection")
    lines.append("")
    rows = []
    for rec in m["records"]:
        by_class: dict[str, int] = {}
        for item in rec["projection"]:
            by_class[item["loss_class"]] = by_class.get(item["loss_class"], 0) + 1
        rows.append([
            f"`{rec['entity_id']}`", rec["entity_kind"], rec["leaf_paths"],
            len(rec["projection"]), by_class.get("L1", 0), by_class.get("L2", 0),
            by_class.get("L3", 0), len(rec["uncovered"]),
            f"`{rec['bitemporal']['valid_time_resolution']}`",
            ", ".join(rec.get("flags", [])) or "—",
        ])
    lines.append(table(["entity", "kind", "leaves", "projected", "L1", "L2", "L3",
                        "uncovered", "valid_time", "flags"], rows))
    lines.append("")

    lines.append("## 3. Epistemic conservativeness (recorded vs policy cap)")
    lines.append("")
    rows = []
    for rec in m["records"]:
        pol = rec.get("epistemic_policy")
        if not pol:
            continue
        rows.append([f"`{rec['entity_id']}`", pol["recorded"], pol["cap"],
                     "yes" if pol["over_grade"] else "no",
                     "—" if pol["delta"] is None else f"{pol['delta']:+d}", pol["basis"]])
    lines.append(table(["claim", "recorded", "cap (T-5.2)", "over-grade", "delta", "basis"], rows))
    lines.append("")
    lines.append("A recorded status above the cap is **flagged, never rewritten**; the disclosure "
                 "register (`D-06`) holds the ruling request.")
    lines.append("")

    lines.append("## 4. Measured cross-checks")
    lines.append("")
    cross = m["cross_checks"]
    rows = [
        ["claim↔evidence reference symmetry",
         f"{cross['evidence_ref_symmetry']['symmetric']}/{cross['evidence_ref_symmetry']['pairs']} claims symmetric"],
        ["provenance coverage",
         f"{cross['provenance_coverage']['reachable_via_activity_used_entities']}/"
         f"{cross['provenance_coverage']['records']} records reachable via `activity.used_entities`"],
        ["provenance granularity", cross["provenance_coverage"]["granularity"]],
        ["software versions",
         f"{cross['software_version_missing']['empty_version']}/"
         f"{cross['software_version_missing']['entries']} entries empty"],
        ["quote elision",
         f"{cross['quote_elision']['with_elision']}/{cross['quote_elision']['quotes']} quotes elided"],
        ["quote char offsets",
         f"{cross['quote_char_offsets']['with_start_offset']}/{cross['quote_char_offsets']['quotes']} with start_offset"],
        ["evidence assessment present",
         f"{cross['evidence_assessment_present']['with_assessment']}/"
         f"{cross['evidence_assessment_present']['records']} records carry an assessment block"],
        ["review events in pilot", cross["review_events_in_pilot"]],
        ["KO link style",
         f"{cross['ko_claim_refs_usage']['using_relations']}/{cross['ko_claim_refs_usage']['kos']} KOs use "
         f"`relations[]`, {cross['ko_claim_refs_usage']['using_claim_refs']} use `claim_refs`"],
        ["identity groups",
         "; ".join(f"token {g['token']}: " + ", ".join(f"`{i}`" for i in g["ids"]) +
                   (" (fragmented)" if g["fragmented"] else "")
                   for g in cross["identity_groups"])],
    ]
    lines.append(table(["check", "measured value"], rows))
    lines.append("")

    lines.append("## 5. Loss register")
    lines.append("")
    rows = [[d["id"], d["class"], d["severity"], d["title"], len(d["affected"]), d["disposition"]]
            for d in m["disclosures"]]
    lines.append(table(["id", "class", "severity", "title", "affected", "disposition"], rows))
    lines.append("")

    lines.append("## 6. Validation results")
    lines.append("")
    if v.get("results"):
        rows = [[r["id"], r["check"], "PASS" if r["pass"] else "FAIL", r["detail"]]
                for r in v["results"]]
        lines.append(table(["id", "check", "result", "detail"], rows))
        lines.append("")
        lines.append(f"**{v['passed']}/{v['checks']} checks passed.**")
    else:
        lines.append("_runs/ke_mapping_validation.json missing: run "
                     "`python scripts/validate_ke_mapping.py`._")
    lines.append("")

    lines.append("## 7. Retrieval demonstrations")
    lines.append("")
    rows = []
    for case in m["retrieval_demonstrations"]:
        resp = case["response"]
        size = (resp.get("total") or len(resp.get("nodes", [])) or len(resp.get("steps", []))
                or resp.get("status"))
        rows.append([case["class"], json.dumps(case["request"], ensure_ascii=False)[:110], size])
    lines.append(table(["query class", "request", "items/nodes/steps"], rows))
    lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    document = render()
    path = os.path.join(ROOT, OUT)
    if args.check:
        existing = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if existing != document:
            print(f"STALE: {OUT} does not match a fresh render")
            return 1
        print(f"OK: {OUT} is up to date")
        return 0
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(document)
    print(f"wrote {OUT} ({len(document)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())