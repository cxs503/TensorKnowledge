REPO = Path(__file__).resolve().parents[1]
AD = REPO / "artifacts" / "ke_eval"
API = os.environ.get("TENSOR_API_BASE", "http://127.0.0.1:8010").rstrip("/")
USER = os.environ.get("TENSOR_AGENT_USER", "agent")
PASS = os.environ.get("TENSOR_AGENT_PASS", "")


def load(name):
    p = AD / name
    return json.loads(p.read_text()) if p.exists() else {}


def login() -> str:
    data = urllib.parse.urlencode({"username": USER, "password": PASS}).encode()
    req = urllib.request.Request(f"{API}/auth/login", data=data,
                                 headers={"Content-Type": "application/x-www-form-urlencoded"})
    with urllib.request.urlopen(req, timeout=30) as r:
        d = json.loads(r.read())
    return d.get("access_token") or d.get("token")


