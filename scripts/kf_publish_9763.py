"""Publish the wp-9763-01 progress report to the platform (POST /tensor/reports).

Reads runs/wp-9763-01/platform_report.json (generated by scripts/kf_report_9763.py) so the posted body
is byte-identical to docs/kf/wp-9763-01/KF-RESULT-wp-9763-01.md.

Usage: python3 scripts/kf_publish_9763.py
"""
from __future__ import annotations

import json
import os
import pathlib
import sys
import urllib.request

BASE = os.environ.get("TENSOR_API_BASE", "http://127.0.0.1:8010/api/v1").rstrip("/")
PAYLOAD = pathlib.Path("runs/wp-9763-01/platform_report.json")


def _req(url, payload=None, token=None):
    data = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json"})
    if token:
        req.add_header("Authorization", "Bearer " + token)
    with urllib.request.urlopen(req, timeout=180) as r:
        return json.loads(r.read().decode())


def login():
    user = os.environ.get("TENSOR_AGENT_USER")
    pwd = os.environ.get("TENSOR_AGENT_PASS")
    for path in ("/auth/login", "/auth/token", "/login"):
        try:
            d = _req(BASE + path, {"username": user, "password": pwd})
        except Exception:
            continue
        tok = d.get("access_token") or d.get("token") or (d.get("data") or {}).get("access_token")
        if tok:
            return tok
    return None


def main() -> int:
    payload = json.loads(PAYLOAD.read_text())
    tok = login()
    res = _req(BASE + "/tensor/reports", payload, token=tok)
    if isinstance(res, dict) and isinstance(res.get("data"), dict):
        res = res["data"]
    print("posted report id:", res.get("id"), "title:", res.get("title"), "status:", res.get("status"))
    print("tags:", res.get("tags"))
    print("markdown chars:", len(res.get("markdown") or ""), "figures:", len(res.get("figures") or []))
    return 0 if res.get("id") else 1


if __name__ == "__main__":
    sys.exit(main())