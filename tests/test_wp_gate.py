def _mutated_registry(tmp_path: Path, mutate) -> dict:
    doc = load(REGISTRY)
    mutate(doc)
    path = tmp_path / "registry.json"
    path.write_text(json.dumps(doc, ensure_ascii=False), encoding="utf-8")
    return g.validate_skill_registry(path)


def test_registered_skill_needs_a_review_event_and_reuse_counter(tmp_path):
    def mutate(doc):
        skill = doc["skills"][0]
        skill["lifecycle_state"] = "registered"
        skill["sample_tests"] = [{"report_id": "1", "source_hash": "sha256:" + "d" * 64,
                                  "outcome": "pass"}]
        skill["updated_at"] = "2026-11-12T00:00:00Z"
        # review present but without a review_event_id -> K5
        skill["review"] = {"reviewed_at": "2026-11-12T00:00:00Z",
                           "reviewer_id": "reviewer-3f2c9a1b", "reviewer_type": "person"}
        skill.pop("reuse_count", None)

    result = _mutated_registry(tmp_path, mutate)
    assert not result["pass"]
    names = {c["name"] for c in result["checks"] if not c["ok"]}
    assert "K4.lifecycle_preconditions" in names
    assert "K5.review_auditable" in names


def test_sample_tested_requires_a_passing_sample(tmp_path):
    def mutate(doc):
        doc["skills"][1]["lifecycle_state"] = "sample-tested"
        doc["skills"][1]["sample_tests"] = [{"report_id": "1", "source_hash": "sha256:" + "d" * 64,
                                             "outcome": "fail"}]

    result = _mutated_registry(tmp_path, mutate)
    assert "K4.lifecycle_preconditions" in {c["name"] for c in result["checks"] if not c["ok"]}


def test_missing_report_type_breaks_six_type_coverage(tmp_path):
    def mutate(doc):
        doc["skills"] = [s for s in doc["skills"] if s["report_type"] != "experimental-validation"]

    result = _mutated_registry(tmp_path, mutate)
    assert "K6.six_type_coverage" in {c["name"] for c in result["checks"] if not c["ok"]}


