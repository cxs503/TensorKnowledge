def test_ladder_cannot_reach_l3_without_a_matching_confirmed_ticket():
    digest = "sha256:" + "a" * 64
    base = dict(structural_ok=True, evidence_ok=True, review_state="approved",
                package_id="wp-x", claims_sha256=digest)

    for ticket, expected in [
        (None, "MISSING_PLATFORM_VERIFICATION_TICKET"),
        ({"gate": "confirmed", "package_id": "wp-x", "claims_sha256": digest}, "TICKET_UNSIGNED"),
        ({"gate": "pending", "package_id": "wp-x", "claims_sha256": digest,
          "issued_by": "tensorplatform/verification-gate"}, "TICKET_NOT_CONFIRMED"),
        ({"gate": "confirmed", "package_id": "wp-y", "claims_sha256": digest,
          "issued_by": "tensorplatform/verification-gate"}, "TICKET_PACKAGE_MISMATCH"),
        ({"gate": "confirmed", "package_id": "wp-x", "claims_sha256": "sha256:" + "b" * 64,
          "issued_by": "tensorplatform/verification-gate"}, "TICKET_CLAIMS_DIGEST_MISMATCH"),
    ]:
        out = g.verification_level(ticket=ticket, **base)
        assert out["level"] == "L2", ticket
        assert out["ceiling_reason"] == expected, ticket

    ok = g.verification_level(
        ticket={"gate": "confirmed", "package_id": "wp-x", "claims_sha256": digest,
                "issued_by": "tensorplatform/verification-gate"}, **base
    )
    assert ok["level"] == "L3"

    not_approved = g.verification_level(
        ticket={"gate": "confirmed", "package_id": "wp-x", "claims_sha256": digest,
                "issued_by": "tensorplatform/verification-gate"},
        **{**base, "review_state": "in-review"}
    )
    assert not_approved["level"] == "L2"
    assert not_approved["ceiling_reason"] == "REVIEW_NOT_APPROVED"


def test_gate_failures_cap_the_level():
    digest = "sha256:" + "a" * 64
    ticket = {"gate": "confirmed", "package_id": "wp-x", "claims_sha256": digest,
              "issued_by": "tensorplatform/verification-gate"}
    out = g.verification_level(structural_ok=False, evidence_ok=True, review_state="approved",
                               ticket=ticket, package_id="wp-x", claims_sha256=digest)
    assert (out["level"], out["ceiling_reason"]) == ("L0", "STRUCTURAL_GATE_FAILED")
    out = g.verification_level(structural_ok=True, evidence_ok=False, review_state="approved",
                               ticket=ticket, package_id="wp-x", claims_sha256=digest)
    assert (out["level"], out["ceiling_reason"]) == ("L1", "EVIDENCE_GATE_FAILED")


