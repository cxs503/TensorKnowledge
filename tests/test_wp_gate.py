    assert "attachments_manifest" in _validate_contract(with_attachment)

    def with_manifest(d):
        with_attachment(d)
        d["input"]["attachments_manifest"] = "tensor://reports/9001/attachments.json"

    assert _validate_contract(with_manifest) == ""


