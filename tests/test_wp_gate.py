"""Tests for the three-gate validator (``ke/wp_gate.py``).

The fixtures under ``tests/fixtures/extraction/`` are generated by
``scripts/build_extraction_fixtures.py`` from two synthetic sources, so every
assertion here is about behaviour of the gate, not about a real report.

Covered:
* G1 structural pass/fail — one fixture per rule family that can fail on its own;
* G2 evidence pass/fail — reachability, hash, locator offsets, coverage;
* the legal empty package (``no_forced_claim_generation``);
* the verification ladder — L2 ceiling without a ticket, L3 only with a confirmed
  platform ticket whose claims digest matches;
* the axis separation — mission state is never consumed, self-approval is refused;
* the review packet cannot carry the producer's explanation, and the reviewer
  prompt is measurably not the producer prompt;
* the contract schema branches (process 03 / 04 / 05, attachment manifest);
* the Extraction Skill Library lifecycle rules K1–K6.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

import jsonschema
import pytest

from ke import wp_gate as g

FIX = Path(__file__).resolve().parent / "fixtures" / "extraction"
SOURCES = FIX / "sources"
REGISTRY = Path(__file__).resolve().parents[1] / "extraction-skills" / "registry.json"
LEDGERS = FIX / "ledgers"   # review ledgers live outside the producer package (S15)
TICKETS = FIX / "tickets"   # platform verification tickets, likewise
VERIFIED_TICKET = TICKETS / "wp-ok-verified.verification_ticket.json"

PRODUCER = "agent-synthetic-0000"


def run(name: str, **kwargs) -> dict:
    kwargs.setdefault("review_ledger_dir", LEDGERS)
    kwargs.setdefault("tickets_dir", TICKETS)
    return g.run_gates(FIX / name, g.DirSourceResolver(SOURCES), **kwargs)


def failed(report: dict, gate: str) -> list[str]:
    return [c["name"] for c in report[gate]["checks"] if not c["ok"]]


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


