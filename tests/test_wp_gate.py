def test_review_request_carries_source_and_objects_only():
    report = run("ok-basic")
    request = report["semantic"]["request"]
    assert set(request["context"]) == {"source", "claims", "evidence", "provenance"}
    assert g.context_leaks(request) == []
    serialized = json.dumps(request["context"])
    assert "self_assessment" not in serialized
    assert "extraction_summary" not in serialized
    # the exclusion is stated for the reviewer, so it is auditable
    assert any("extraction_summary" in item for item in request["excluded"])
    assert request["sample"]["claims_total"] == 5
    assert request["sample"]["claims_to_open"] == 5  # sample_rate 1.0 in the contract


def test_context_leaks_detects_injected_producer_explanation():
    report = run("ok-basic")
    packet = copy.deepcopy(report["semantic"]["request"])
    packet["context"]["claims"][0]["producer_rationale"] = "trust me"
    packet["context"]["notes"] = "free prose"
    leaks = g.context_leaks(packet)
    assert "context.notes" in leaks
    assert any(leak.startswith("context.claims[0].producer_rationale") for leak in leaks)


def test_reviewer_prompt_is_not_the_producer_prompt():
    producer, reviewer = g.build_review_prompts("technical-proposal", "9001")
    assert g.prompt_similarity(producer, reviewer) < 0.5
    # the shipped prompt files must also be independent of each other
    prompts = Path(__file__).resolve().parents[1] / "extraction-skills" / "prompts"
    shipped = g.prompt_similarity((prompts / "producer-v1.md").read_text(encoding="utf-8"),
                                  (prompts / "reviewer-v1.md").read_text(encoding="utf-8"))
    assert shipped < 0.5, shipped

    # copying the producer prompt into the reviewer slot must fail M4
    report = g.run_gates(FIX / "ok-basic", g.DirSourceResolver(SOURCES),
                         producer_prompt=producer, reviewer_prompt=producer)
    assert "M4.prompt_independent" in failed(report, "semantic")


