def test_ok_basic_passes_both_programmatic_gates():
    report = run("ok-basic")
    assert report["verdict"] == "PASS_PROGRAMMATIC_PENDING_REVIEW"
    assert failed(report, "structural") == [], failed(report, "structural")
    assert failed(report, "evidence") == [], failed(report, "evidence")
    assert report["counts"] == {"claims": 5, "evidence": 4, "provenance": 4, "unresolved": 1}
    # semantic gate is never passed by code
    assert report["semantic"]["pass"] is None
    assert report["semantic"]["status"] == "pending-independent-review"
    assert report["semantic"]["detail"]["M5_semantic_fidelity"].startswith("not_run")


