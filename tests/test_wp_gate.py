def test_mission_state_is_not_consumed_by_the_gate():
    report = run("ok-basic")
    assert report["axes"]["mission_state"].startswith("not consumed")
    # a ticket plus an approved ledger still cannot come from mission success:
    # without a ledger the review axis stays draft and L3 is unreachable.
    no_ledger = g.run_gates(FIX / "ok-verified", g.DirSourceResolver(SOURCES),
                            review_events=[], ticket=load(VERIFIED_TICKET))
    assert no_ledger["axes"]["review_state"] == "draft"
    assert no_ledger["verification"]["level"] == "L2"
    assert no_ledger["verification"]["ceiling_reason"] == "REVIEW_NOT_APPROVED"


