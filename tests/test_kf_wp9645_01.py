"""Acceptance regression suite for work package wp-9645-01 (task_type=01, report 9645).

Package: ``docs/kf/wp-9645-01`` — asset registration for report 9645
(IN101-N09 ISO 19906 ice-pressure partial-factor back-calibration, scenario
``ice_partial_factors_target_inverse``).

Why these tests exist
---------------------
The registered package pinned the source markdown SHA-256
(``a8bb8902…fb00``, 11824 chars) but did **not** keep the hashed bytes in the
tree, so every derived constant (8 section hashes, ``locator_check.json``,
``sha256.txt``) was only re-checkable by re-asking the platform API — i.e. the
"hash self-证" item passed by trust, not by recomputation. This suite pins the
missing evidence layer (``source/report_9645.md`` + ``source/record_9645.json``,
captured by ``scripts/kf/wp_9645_01_snapshot.py``) and then re-derives every
committed artefact from it, offline:

* the pinned source hash / char count / byte count / line count are recomputed
  from the committed snapshot bytes;
* ``asset_manifest.json`` is rebuilt with ``build_manifest(record)`` from the
  snapshot and must equal the committed manifest field-for-field (only
  ``generated_at`` is allowed to differ, it is wall-clock);
* ``asset_manifest.schema.json``, ``locator_check.json``, ``report_body.md``,
  ``source.md`` and ``sha256.txt`` must be regenerated byte-identically;
* the embedded manifest in ``kf_result.json`` must equal the on-disk manifest;
* relative / module / endpoint locators must resolve verbatim in the snapshot at
  the recorded 1-based line, with the recorded occurrence count;
* ``asset_coverage.png`` must be the real matplotlib figure, not the 1x1
  no-matplotlib fallback;
* negative controls: a single flipped character in the snapshot must turn the
  snapshot verifier and the locator gate red, and the capture tool must refuse
  to overwrite a good snapshot with a drifted payload.

No network and no API credentials are needed to run the suite.

Run:  python3 -m pytest tests/test_kf_wp9645_01.py -q
"""
