def _read_text(path: str) -> str:
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


# ---------------------------------------------------------------------------
# 1. source evidence: the pinned hash is recomputed from committed bytes
# ---------------------------------------------------------------------------
def test_snapshot_is_committed_and_reproduces_pinned_source_hash(manifest, snapshot_bytes):
    src = manifest["source_asset"]
    assert os.path.isfile(SNAPSHOT_MD), "source snapshot missing — hash is only re-checkable online"
    computed = hashlib.sha256(snapshot_bytes).hexdigest()
    assert "sha256:" + computed == src["hash"]["value"] == src["hash"]["contract_expected"]
    assert src["hash"]["matches_contract"] is True
    text = snapshot_bytes.decode("utf-8")
    assert len(text) == src["size"]["chars"] == src["size"]["contract_chars"] == 11824
    assert len(snapshot_bytes) == src["size"]["bytes_utf8"] == 15967
    assert text.count("\n") + 1 == src["size"]["lines"] == 196


def test_snapshot_provenance_is_self_consistent(manifest, snapshot_tool, snapshot_bytes, snapshot):
    with open(SNAPSHOT_META, encoding="utf-8") as f:
        meta = json.load(f)
    assert meta["package_id"] == "wp-9645-01"
    assert meta["report_id"] == "9645"
    assert meta["snapshot_file"] == "docs/kf/wp-9645-01/source/report_9645.md"
    assert meta["snapshot"]["sha256"] == manifest["source_asset"]["hash"]["value"]
    assert meta["snapshot"]["chars"] == len(snapshot)
    assert meta["snapshot"]["bytes_utf8"] == len(snapshot_bytes)
    assert meta["snapshot"]["lines"] == snapshot.count("\n") + 1
    assert meta["pinned"]["sha256"] == manifest["source_asset"]["hash"]["value"]
    # the recorded verdict is not trusted: it is recomputed here
    verdict = snapshot_tool.verify_snapshot(snapshot_bytes, snapshot_tool.pinned_targets(manifest))
    assert verdict["all_pass"] is True
    assert all(c["pass"] for c in verdict["checks"])
    assert {c["item"] for c in verdict["checks"]} == {"sha256", "chars", "bytes_utf8", "lines"}
    assert meta["verify"]["all_pass"] is True


