# 6. negative controls: the gates above must be falsifiable
# ---------------------------------------------------------------------------
def test_snapshot_verifier_rejects_a_single_flipped_char(manifest, snapshot_tool, snapshot_bytes):
    targets = snapshot_tool.pinned_targets(manifest)
    assert snapshot_tool.verify_snapshot(snapshot_bytes, targets)["all_pass"] is True
    tampered = snapshot_bytes.replace(b"ISO 19906", b"ISO 19907", 1)
    assert tampered != snapshot_bytes
    verdict = snapshot_tool.verify_snapshot(tampered, targets)
    assert verdict["all_pass"] is False
    failed = {c["item"] for c in verdict["checks"] if not c["pass"]}
    assert "sha256" in failed


def test_locator_gate_rejects_a_tampered_section(manifest, register, snapshot):
    assert register.build_locator_check(manifest, snapshot)["all_pass"] is True
    poisoned = dict(manifest)
    poisoned["sections"] = [dict(s) for s in manifest["sections"]]
    poisoned["sections"][3]["sha256"] = "sha256:" + "0" * 64
    verdict = register.build_locator_check(poisoned, snapshot)
    assert verdict["all_pass"] is False
    assert [c["pass"] for c in verdict["checks"]].count(False) == 1


def test_capture_tool_refuses_to_overwrite_on_source_drift(
    snapshot_tool, snapshot_bytes, record_file, monkeypatch
):
    """A drifted upstream payload must abort before the good snapshot is touched."""
    drifted = dict(record_file)
    drifted["markdown"] = snapshot_bytes.decode("utf-8").replace("ISO 19906", "ISO 19907", 1)
    monkeypatch.setenv("TENSOR_API_BASE", "http://127.0.0.1:0/api/v1")
    monkeypatch.setattr(snapshot_tool, "api_get", lambda path: drifted)
    assert snapshot_tool.do_fetch() == 1
    with open(SNAPSHOT_MD, "rb") as f:
        assert f.read() == snapshot_bytes, "capture tool overwrote a verified snapshot"


def test_pinned_targets_are_read_from_the_manifest_not_hardcoded(manifest, snapshot_tool):
    targets = snapshot_tool.pinned_targets(manifest)
    src = manifest["source_asset"]
