def test_sections_rederived_from_snapshot(manifest, register, snapshot):
    sections = register.index_sections(snapshot)
    assert sections == manifest["sections"]
    assert len(sections) == 8
    assert [s["ordinal"] for s in sections] == list(range(1, 9))
    assert sections[0]["heading"].startswith("IN101-N09 — ISO 19906")
    assert [s["level"] for s in sections] == [1, 2, 2, 2, 2, 2, 2, 2]
    # every section body is bounded by the next heading (no gaps / no overlaps)
    assert sections[0]["line_start"] == 1
    assert sections[-1]["line_end"] == snapshot.count("\n") + 1
    for prev, nxt in zip(sections, sections[1:]):
        assert nxt["line_start"] == prev["line_end"] + 1
    assert sum(s["chars"] for s in sections) <= len(snapshot)


def test_manifest_is_fully_regenerable_from_snapshot(manifest, register, record):
    rebuilt = register.build_manifest(record)
    assert rebuilt["generated_at"] != "" and manifest["generated_at"] != ""
    rebuilt.pop("generated_at")
    committed = dict(manifest)
    committed.pop("generated_at")
    assert rebuilt == committed


def test_locator_check_passes_and_regenerates_exactly(locator, manifest, register, snapshot):
    assert locator["all_pass"] is True
    assert locator["total_sections"] == len(manifest["sections"]) == 8
    assert locator["checks"] == register.build_locator_check(manifest, snapshot)["checks"]
    for check in locator["checks"]:
        assert check["pass"] is True
        assert check["expected_sha256"] == check["computed_sha256"]
    # the pinned section hashes are the ones recomputed from the snapshot bytes
    assert [c["expected_sha256"] for c in locator["checks"]] == [
        s["sha256"] for s in manifest["sections"]
    ]


