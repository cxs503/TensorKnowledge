# ---------------------------------------------------------------------------
# 7. falsifiability experiment artefact (numbers re-derived, not read off)
# ---------------------------------------------------------------------------
def test_gate_sensitivity_artefact_matches_live_recomputation(manifest, register, snapshot, snapshot_tool):
    with open(os.path.join(PKG, "gate_sensitivity.json"), encoding="utf-8") as f:
        recorded = json.load(f)
    assert recorded["sections"] == len(manifest["sections"]) == 8
    assert recorded["source_chars"] == len(snapshot) == 11824
    # gate A: 1:1 detection, no false positive at k=0
    rows = recorded["gate_a_locator"]
    assert [r["tampered_sections"] for r in rows] == list(range(9))
    assert rows[0]["failed_checks"] == 0 and rows[0]["gate_all_pass"] is True
    for row in rows[1:]:
        assert row["failed_checks"] == row["tampered_sections"]
        assert row["gate_all_pass"] is False
    # live recomputation of the two extremes (k=0 clean, k=8 fully poisoned)
    assert register.build_locator_check(manifest, snapshot)["all_pass"] is True
    poisoned = json.loads(json.dumps(manifest))
    for sec in poisoned["sections"]:
        sec["sha256"] = "sha256:" + "0" * 64
    full = register.build_locator_check(poisoned, snapshot)
    assert full["all_pass"] is False
    assert sum(1 for c in full["checks"] if not c["pass"]) == 8 == rows[-1]["failed_checks"]
    # gate B: a single flipped character is already fatal
    rows_b = recorded["gate_b_snapshot"]
    assert rows_b[0]["verify_all_pass"] is True and rows_b[0]["detected"] is False
    assert all(r["detected"] for r in rows_b[1:])
    targets = snapshot_tool.pinned_targets(manifest)
    assert snapshot_tool.verify_snapshot(snapshot.encode("utf-8"), targets)["all_pass"] is True
    assert (
        snapshot_tool.verify_snapshot(
            snapshot.replace("ISO 19906", "ISO 19907", 1).encode("utf-8"), targets
        )["all_pass"]
        is False
    )
    assert recorded["all_pass"] is True and all(recorded["checks"].values())
    assert os.path.isfile(os.path.join(PKG, "gate_sensitivity.png"))
