"""Contract gate for the shared KF-RESULT v1 envelope schema.

The schema ``schemas/kf_result.v1.schema.json`` is the acceptance surface every
work package in this repository is validated against, so it has to be a
*superset* of the committed artifact family — and it has to keep the gates that
actually carry evidence:

* identity  — ``package_id`` / ``task_type`` / ``report_id`` present and shaped;
* provenance — ``source_field`` + ``source_hash`` present, hash a real
  ``sha256:<64 hex>`` string (this is the only field the platform recomputes);
* outputs    — a non-empty artifact map (a package that produced nothing is not
  a delivered package);
* claims     — typed when present, ``verified`` is not a legal claim status.

These tests exist because the schema file was once overwritten in place by a
narrower contract, which silently turned ~70 package acceptance tests red on
``main`` (each package only validates its own envelope, so nobody saw it).
The census is regenerated byte-for-byte from the committed bytes, so this gate
cannot be satisfied by editing the recorded numbers.
"""

from __future__ import annotations

import copy
import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT / "schemas" / "kf_result.v1.schema.json"
AUDIT_PATH = ROOT / "scripts" / "kf" / "audit_envelope_conformance.py"
CENSUS_PATH = ROOT / "docs" / "kf" / "wp-459-01" / "envelope_conformance.json"
WP459_ENVELOPE = ROOT / "docs" / "kf" / "wp-459-01" / "kf_result.json"

jsonschema = pytest.importorskip("jsonschema")


@pytest.fixture(scope="module")
def schema() -> dict:
    return json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def validator(schema):
    return jsonschema.Draft202012Validator(schema)


@pytest.fixture(scope="module")
def audit():
    spec = importlib.util.spec_from_file_location(
        "audit_envelope_conformance", AUDIT_PATH
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)  # type: ignore[union-attr]
    return module


@pytest.fixture(scope="module")
def census(audit) -> dict:
    return audit.census()


def _envelope(**overrides) -> dict:
    env = {
        "package_id": "wp-0000-01",
        "task_type": "01-asset-registration",
        "report_id": "1",
        "provenance": {
            "source_field": "markdown",
            "source_hash": "sha256:" + "0" * 64,
        },
        "outputs": {"asset_manifest.json": {"assets": []}},
    }
    env.update(overrides)
    return env


# --------------------------------------------------------------------------
# 1. the repaired schema actually describes the committed family
# --------------------------------------------------------------------------
def test_census_regenerates_byte_for_byte(census, audit, monkeypatch):
    """The recorded census must be reproducible from the current bytes."""
    monkeypatch.setattr(audit, "ROOT", str(ROOT))
    assert audit.dumps(census) == CENSUS_PATH.read_text(encoding="utf-8")


def test_residual_allowlist_is_exact(census):
    """Only the declared legacy envelopes may fail; never a blanket tolerance."""
    assert census["residual_allowlist_matches"] is True
    residual = set(census["nonconforming"]) | set(census["pre_envelope_legacy"])
    assert residual == set(census["residual_allowlist"])
    for path in census["residual_allowlist"]:
        assert (ROOT / path).exists(), f"stale allowlist entry: {path}"


def test_residual_entries_really_fail(census, validator):
    """Allowlisted files must still be non-conforming (no silent laundering)."""
    for path in census["nonconforming"]:
        doc = json.loads((ROOT / path).read_text(encoding="utf-8"))
        assert list(validator.iter_errors(doc)), (
            f"{path} now conforms; drop it from the allowlist"
        )
    for path in census["pre_envelope_legacy"]:
        doc = json.loads((ROOT / path).read_text(encoding="utf-8"))
        assert not ("provenance" in doc and "outputs" in doc)


def test_family_conformance_ratio_does_not_regress(census):
    """Measured coverage of the artifact family (baseline: 161/162 = 99.4%)."""
    counts = census["counts"]
    assert counts["envelopes"] >= 160, "census collapsed — glob or checkout is broken"
    assert counts["conforming"] / counts["envelopes"] >= 0.99
    # rev 1.0 rejected every envelope carrying the contract-mandated claims key
    assert counts["envelopes_declaring_claims_key"] >= 100


def test_claims_carrying_envelope_is_accepted(validator, census):
    """Regression guard: the 01 contract mandates `claims: []`, so the key is legal."""
    assert census["counts"]["envelopes_declaring_claims_key"] > 0
    validator.validate(_envelope(claims=[]))


# --------------------------------------------------------------------------
# 2. the schema still fails what it must fail
# --------------------------------------------------------------------------
def test_wp459_envelope_conforms(validator):
    validator.validate(json.loads(WP459_ENVELOPE.read_text(encoding="utf-8")))


@pytest.mark.parametrize(
    "mutation",
    [
        pytest.param(lambda e: e.pop("provenance"), id="no-provenance"),
        pytest.param(lambda e: e["provenance"].pop("source_hash"), id="no-source-hash"),
        pytest.param(
            lambda e: e["provenance"].pop("source_field"), id="no-source-field"
        ),
        pytest.param(
            lambda e: e["provenance"].update(source_hash="sha256:deadbeef"),
            id="short-hash",
        ),
        pytest.param(
            lambda e: e["provenance"].update(source_hash="0" * 64),
            id="hash-without-algorithm",
        ),
        pytest.param(
            lambda e: e["provenance"].update(source_field="body"), id="bad-source-field"
        ),
        pytest.param(lambda e: e.pop("outputs"), id="no-outputs"),
        pytest.param(lambda e: e.update(outputs={}), id="empty-outputs"),
        pytest.param(lambda e: e.pop("package_id"), id="no-package-id"),
        pytest.param(lambda e: e.update(package_id="459-01"), id="bad-package-id"),
        pytest.param(lambda e: e.update(task_type="02-extraction"), id="bad-task-type"),
        pytest.param(lambda e: e.update(report_id=459), id="non-string-report-id"),
        pytest.param(lambda e: e.update(revision=2), id="unknown-top-level-key"),
        pytest.param(
            lambda e: e.update(
                claims=[{"claim_id": "c-1", "text": "t", "status": "verified"}]
            ),
            id="verified-is-not-a-claim-status",
        ),
        pytest.param(
            lambda e: e.update(claims=[{"claim_id": "c-1", "text": "t"}]),
            id="claim-without-status",
        ),
    ],
)
def test_schema_rejects_broken_envelopes(validator, mutation):
    env = copy.deepcopy(_envelope())
    mutation(env)
    with pytest.raises(jsonschema.ValidationError):
        validator.validate(env)


def test_short_task_type_codes_stay_legal(validator):
    """Three accepted packages declare the bare code (`01`) instead of the full name."""
    validator.validate(_envelope(task_type="01"))


def test_provenance_metadata_keys_are_tolerated(validator):
    """Provenance extras are per-work-package evidence, not envelope structure."""
    env = _envelope()
    env["provenance"].update(
        source_uri="tensor://reports/1",
        producer="scripts/kf/register_assets.py",
        emitted_at="2026-11-12T00:00:00Z",
        notes="hash recomputed from GET /tensor/reports/1 markdown",
        lane="kf-01",
        hash_algo="sha256",
        source_chars=7586,
    )
    validator.validate(env)
    with pytest.raises(jsonschema.ValidationError):
        broken = copy.deepcopy(env)
        broken["provenance"]["source_hash"] = None
        validator.validate(broken)
